/**
 * Every TypeScript project in the repo, checked with `bun check`, or with
 * `tsc` under `--tsc`. Names narrow it: `bun run typecheck core orm`.
 *
 * One list for both checkers, so a project cannot be checked by one and
 * missed by the other. CI runs `tsc` where `bun check` does not exist yet
 * (the Bun 1.4.0 job, which keeps `engines` honest) and `bun check`
 * everywhere else, so the two are compared on every push rather than
 * assumed to agree.
 *
 * Measured on this machine under Bun 1.4.3, two adjacent runs each with a
 * CPU control flat at 45 to 55 ms: `tsc` took 2.2 to 7.8 s a project, 66 s
 * for all twelve, and `bun check` 0.1 to 0.6 s, 3.6 s for all twelve. With
 * errors planted in five projects (a type error in core, a bad call in a
 * plugin, an unresolvable subpath, a type imported as a value, JSX against
 * `createElement`), the two reported the same errors by file, line and code.
 */

type Project = {
  name: string
  config: string
  /** Checked with `-b`, following its references. */
  build?: true
  /** Run first: what the project's tsconfig chain is generated by. */
  before?: string[]
}

const PROJECTS: Project[] = [
  { name: 'core', config: 'packages/core/tsconfig.json' },
  { name: 'orm', config: 'packages/orm/tsconfig.json' },
  { name: 'cli', config: 'packages/cli/tsconfig.json' },
  { name: 'create', config: 'packages/create/tsconfig.json' },
  { name: 'vue', config: 'packages/plugins/vue/tsconfig.json' },
  { name: 'analytics', config: 'packages/plugins/analytics/tsconfig.json' },
  { name: 'dashboard', config: 'packages/plugins/dashboard/tsconfig.json' },
  { name: 'db-explorer', config: 'packages/plugins/db-explorer/tsconfig.json' },
  { name: 'example', config: 'apps/example/tsconfig.typecheck.json' },
  {
    name: 'starter',
    config: 'apps/starter/tsconfig.json',
    build: true,
    before: [
      'bun',
      '--cwd',
      'apps/starter',
      '../../packages/cli/src/index.ts',
      '--types',
    ],
  },
  { name: 'tests', config: 'tests/tsconfig.json' },
  { name: 'scripts', config: 'scripts/tsconfig.json' },
]

const args = process.argv.slice(2)
const useTsc = args.includes('--tsc')
const names = args.filter(arg => !arg.startsWith('--'))

const unknown = names.filter(name => !PROJECTS.some(p => p.name === name))
if (unknown.length) {
  console.error(
    `No project named ${unknown.join(', ')}. Projects: ${PROJECTS.map(p => p.name).join(', ')}.`,
  )
  process.exit(2)
}

function command(project: Project): string[] {
  if (useTsc) {
    return project.build
      ? ['bunx', 'tsc', '-b', project.config]
      : ['bunx', 'tsc', '-p', project.config, '--noEmit']
  }
  // `--no-pretty` for `tsc`'s own one-line format, which CI logs read best:
  // piped to an agent, `bun check` writes XML-style blocks instead.
  return project.build
    ? ['bun', 'check', '-b', '-p', project.config, '--no-pretty']
    : ['bun', 'check', '-p', project.config, '--no-pretty']
}

const root = `${import.meta.dir}/..`
const tool = useTsc ? 'tsc' : 'bun check'
let failed = 0

for (const project of PROJECTS) {
  if (names.length && !names.includes(project.name)) continue
  const started = performance.now()

  if (project.before) {
    const prep = Bun.spawnSync(project.before, {
      cwd: root,
      stdout: 'pipe',
      stderr: 'pipe',
    })
    if (prep.exitCode !== 0) {
      failed++
      console.log(
        `${project.name}: ${project.before.join(' ')} failed\n${prep.stdout}${prep.stderr}`,
      )
      continue
    }
  }

  const run = Bun.spawnSync(command(project), {
    cwd: root,
    stdout: 'pipe',
    stderr: 'pipe',
  })
  const seconds = ((performance.now() - started) / 1000).toFixed(1)
  if (run.exitCode === 0) {
    console.log(`${project.name}: ${tool}, no errors (${seconds} s)`)
  } else {
    failed++
    console.log(
      `${project.name}: ${tool} failed (${seconds} s)\n${run.stdout}${run.stderr}`,
    )
  }
}

if (failed) {
  console.log(`${failed} project${failed === 1 ? '' : 's'} failed.`)
  process.exit(1)
}
